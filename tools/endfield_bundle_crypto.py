def vfsaes_decrypt(ciphertext):
    blocks = []
    previous = bytearray(VFSAESIV)
    for pos in range(0, len(ciphertext), 16):
        ct = ciphertext[pos:pos+16]
        blk = encrypt_aes_block(previous)
        pt = bytes(c ^ b for c, b in zip(ct, blk))
        blocks.append(pt)
        next_iv = bytearray(16)
        count = 0
        for i in range(16):
            shift_src = (VFSXORKey >> (count & 0x38)) & 0xFF
            temp = blk[i] ^ (31 * i) ^ shift_src
            count += 8
            temp = ((temp >> 5) | (8 * temp)) & 0xFF
            temp = VFSAESSBox[temp]
            next_iv[i] = temp
        previous = next_iv
    return b''.join(blocks)

def decrypt_block(buf: bytearray):
    length = len(buf)
    if length <= 256:
        dec = vfsaes_decrypt(bytes(buf))
        buf[:len(dec)] = dec
    else:
        num_blocks = length // 16
        step = 1 if num_blocks > 256 else (256 // num_blocks)
        n = min(num_blocks, 256)
        dec_buf = bytearray(256)
        for i in range(n):
            dec_buf[i*step : i*step+step] = buf[i*16 : i*16+step]
        dec_buf = bytearray(vfsaes_decrypt(bytes(dec_buf)))
        for i in range(n):
            buf[i*16 : i*16+step] = dec_buf[i*step : i*step+step]

