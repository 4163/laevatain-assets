def xtime(a):
    return (((a << 1) ^ 0x1B) & 0xFF) if (a & 0x80) else (a << 1)

def mix_single_column(a):
    t = a[0] ^ a[1] ^ a[2] ^ a[3]
    u = a[0]
    a[0] ^= t ^ xtime(a[0] ^ a[1])
    a[1] ^= t ^ xtime(a[1] ^ a[2])
    a[2] ^= t ^ xtime(a[2] ^ a[3])
    a[3] ^= t ^ xtime(a[3] ^ u)

def expand_key():
    master_key = VFSAESKey
    rCon = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36, 0x6C, 0xD8, 0xAB, 0x4D, 0x9A, 0x2F, 0x5E, 0xBC, 0x63, 0xC6, 0x97, 0x35, 0x6A, 0xD4, 0xB3, 0x7D, 0xFA, 0xEF, 0xC5, 0x91, 0x39]
    key_cols = [list(master_key[i:i+4]) for i in range(0, len(master_key), 4)]
    iter_size = len(master_key) // 4
    i = 1
    while len(key_cols) < 44:
        word = list(key_cols[-1])
        if len(key_cols) % iter_size == 0:
            word = word[1:] + word[:1]
            word = [VFSAESSBox[b] for b in word]
            word[0] ^= rCon[i]
            i += 1
        prev = key_cols[len(key_cols) - iter_size]
        word = [w ^ p for w, p in zip(word, prev)]
        key_cols.append(word)
    
    round_keys = []
    for x in range(11):
        m = [[0]*4 for _ in range(4)]
        for c in range(4):
            for r in range(4):
                m[c][r] = key_cols[x * 4 + c][r]
        round_keys.append(m)
    return round_keys

ROUND_KEYS = expand_key()

def encrypt_aes_block(plaintext):
    s = [list(plaintext[i:i+4]) for i in range(0, 16, 4)]
    # AddRoundKey 0
    k0 = ROUND_KEYS[0]
    for c in range(4):
        for r in range(4):
            s[c][r] ^= k0[c][r]
    
    for r in range(1, 10):
        # SubBytes
        for c in range(4):
            for row in range(4):
                s[c][row] = VFSAESSBox[s[c][row]]
        # ShiftRows
        s[0][1], s[1][1], s[2][1], s[3][1] = s[1][1], s[2][1], s[3][1], s[0][1]
        s[0][2], s[1][2], s[2][2], s[3][2] = s[2][2], s[3][2], s[0][2], s[1][2]
        s[0][3], s[1][3], s[2][3], s[3][3] = s[3][3], s[0][3], s[1][3], s[2][3]
        # MixColumns
        for c in range(4):
            mix_single_column(s[c])
        # AddRoundKey
        kr = ROUND_KEYS[r]
        for c in range(4):
            for row in range(4):
                s[c][row] ^= kr[c][row]
                
    # Final round
    for c in range(4):
        for row in range(4):
            s[c][row] = VFSAESSBox[s[c][row]]
    s[0][1], s[1][1], s[2][1], s[3][1] = s[1][1], s[2][1], s[3][1], s[0][1]
    s[0][2], s[1][2], s[2][2], s[3][2] = s[2][2], s[3][2], s[0][2], s[1][2]
